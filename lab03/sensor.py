# Предел температуры в градусах Цельсия
предел = float(input())

# Количество записей
n = int(input())

# Счётчики и статистика
всего = 0
ошибки = 0
превышения = 0
сумма = 0.0
количество_верных = 0
максимум = None

# Обработка каждой записи
for _ in range(n):
    запись = input()
    всего += 1

    if запись == "error":
        ошибки += 1
    else:
        показание = float(запись)
        сумма += показание
        количество_верных += 1

        if максимум is None or показание > максимум:
            максимум = показание

        if показание > предел:
            превышения += 1

# Среднее значение по верным показаниям
среднее = сумма / количество_верных

# Вывод результатов
print(всего)
print(ошибки)
print(превышения)
print(f"{максимум:.1f}")
print(f"{среднее:.1f}")
